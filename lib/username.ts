export const USERNAME_PATTERN = /^[a-zA-Z0-9_-]{3,32}$/;

export const RESERVED_USERNAMES = new Set([
  "www",
  "api",
  "app",
  "admin",
  "administrator",
  "root",
  "owner",
  "staff",
  "moderator",
  "status",
  "dashboard",
  "cdn",
  "static",
  "assets",
  "mail",
  "email",
  "smtp",
  "ftp",
  "ssh",
  "raw",
  "avatar",
  "login",
  "logout",
  "register",
  "signup",
  "signin",
  "u",
  "user",
  "users",
  "help",
  "support",
  "blog",
  "docs",
  "about",
  "terms",
  "privacy",
  "legal",
  "billing",
  "dev",
  "test",
  "staging",
  "beta",
  "img",
  "images",
  "file",
  "files",
  "upload",
  "uploads",
  "download",
  "downloads",
  "sharex",
]);

export function isValidUsername(username: string): boolean {
  return USERNAME_PATTERN.test(username) && !RESERVED_USERNAMES.has(username.toLowerCase());
}
